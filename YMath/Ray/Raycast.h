#pragma once
#include "Vector3.h"

// ============================================================
// レイの定義
// ============================================================
struct Ray {
	Vector3 origin;
	Vector3 direction;
};

// ============================================================
// レイキャストのヒット情報
// ============================================================
struct RaycastHit {
	bool isHit = false;     // 当たったかどうか
	float distance = 0.0f;  // 発射位置からの距離
	Vector3 hitPoint;       // 実際に当たったワールド座標
	Vector3 normal;         // 当たった面の法線（壁の向き。跳ね返り計算などに使う）
};