#include "Ground.h"

// ============================================================
// 地面オブジェクトを初期化
// ============================================================
void Ground::Initialize(Camera* camera) {
	camera_ = camera;

	//------------------------------------------------------------
	// Object3dの生成���初期化
	//------------------------------------------------------------
	obj_ = std::make_unique<Object3d>();
	obj_->Initialize();

	// 地面のモデルデータをセットする
	obj_->SetModel("Ground.obj");

	//------------------------------------------------------------
	// ワールドトランスフォームの初期化
	//------------------------------------------------------------
	wt_.Initialize();
}

// ============================================================
// 地面オブジェクトの更新処理
// ============================================================
void Ground::Update() {
	//------------------------------------------------------------
	// ワールド行列の更新
	//------------------------------------------------------------
	wt_.UpdateMatrix();
}

// ============================================================
// 地面オブジェクトの描画処理
// ============================================================
void Ground::Draw() {
	//------------------------------------------------------------
	// 3Dオブジェクトの描画
	//------------------------------------------------------------
	obj_->Draw(camera_, wt_);
}