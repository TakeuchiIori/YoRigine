// 更新処理
// ============================================================
void IdleCombatState::Update([[maybe_unused]] float deltaTime) {
	// ------------------------------------------------------------
	// アイドル中は特にロジック的な更新は行わない
	// この状態は「入力待ち」の意味合いが強く、攻撃・ガードなどの行動入力を監視する
	// ------------------------------------------------------------
}